const pluralIndex = {
  en: (n) => (n === 1 ? 0 : 1),
  pl: (n) => {
    if (n === 1) return 0;
    const ones = n % 10;
    const tens = n % 100;
    if (ones >= 2 && ones <= 4 && !(tens >= 12 && tens <= 14)) return 1;
    return 2;
  }
};

